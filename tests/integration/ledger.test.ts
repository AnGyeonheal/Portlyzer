    expect(uploads[0].jobId).toBe(uploads[1].jobId);
    expect(uploads.filter((job) => job.duplicateFile)).toHaveLength(1);
    const preview = await imports.validateImport(fixture.user, uploads[0].jobId, { mapping: cashMapping, revision: 1 });
